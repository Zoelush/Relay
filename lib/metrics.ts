/**
 * The metric dictionary (phase 14, step R1; docs/REPORTING_PLAN.md). Every number a report shows
 * is defined here once: its formula, the timestamp it's anchored to (which period it falls in),
 * what's included and excluded, and how automation (Zoe, workflows, outbound) is treated.
 * `docs/METRICS.md` is generated from this list (`npm run metrics:doc`), and a test fails if the
 * two differ. Reports compute only what's defined here (R2 on).
 *
 * Shared terms:
 * - **A conversation** is one the customer can see (`visibility` customer): back-office and
 *   tracker tickets are internal and appear only in the ticket dataset. An outbound chat (phase
 *   13) counts once the customer replies to it; until then it's outbound's, not support's.
 * - **A teammate reply** is a public `teammate_reply` written by a teammate. Zoe's replies
 *   (`ai_reply`) and workflows' messages (`workflow_message`) are automation, counted apart.
 * - **Office hours** are the calendar pinned on the conversation when it started (phase 06, the
 *   one source); with none, always open. Durations are given both ways: wall-clock and office hours.
 * - **Periods** are in the report's timezone; a duration falls in the period of its end.
 */
