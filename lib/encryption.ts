/** docs/TRUST.md: the subprocessors, how data is protected, and the keys. */
export function trustDocument() {
  const rows = (cells: string[][]) => cells.map((c) => `| ${c.map((x) => x.replace(/\|/g, "\\|")).join(" | ")} |`).join("\n");
  return `# Subprocessors and encryption

Generated by \`npm run trust:doc\` from \`lib/processors.ts\` and \`lib/encryption.ts\` (phase 16, step C7c). Don't edit by hand; a test compares them. Settings › Security › Subprocessors and encryption shows the same.

## Subprocessors

Every outside service that receives customer data, what it receives, and what a deletion does there.

| Service | Receives | When | Keeps | On deletion |
|---|---|---|---|---|
${rows(PROCESSORS.map((p) => [p.name, p.receives, p.when, p.keeps, DELETION_LABEL[p.deletion]]))}

## How data is protected

| What | How |
|---|---|
${rows(PROTECTIONS.map((p) => [p.what, p.how]))}

## Keys

Each is a deployment secret, set with \`wrangler secret put\`: never in code, configuration or logs.

| Key | Protects | Rotation |
|---|---|---|
${rows(KEYS.map((k) => [`\`${k.name}\``, k.protects, k.rotation]))}
`;
}
