export function language(locale: string, brandLocale = "en") {
  const dictionaries: Record<string, typeof en> = { en, ar, ...more };
  const chain = [
    locale,
    locale.split("-")[0],
    brandLocale,
    brandLocale.split("-")[0],
    "en",
  ];
  const chosen = chain.find((x) => dictionaries[x])!;
  return {
    strings: dictionaries[chosen],
    locale: chosen,
    dir: /^(ar|fa|he|ur)(-|$)/.test(locale) ? "rtl" : "ltr",
  };
}
